def normalize_network_telemetry(
    sysmon_summary: Optional[Dict[str, Any]] = None,
    procmon_summary: Optional[Dict[str, Any]] = None,
    tcpvcon_data: Optional[Union[str, List[Dict[str, Any]]]] = None,
    network_summary: Optional[Dict[str, Any]] = None,
    sample_proc: str = "",
) -> Dict[str, Any]:
    """Aggregate all network telemetry sources, filter noise, and return structured output.

    Args:
        sysmon_summary: Parsed sysmon_summary.json dict.
        procmon_summary: Parsed procmon_summary.json dict.
        tcpvcon_data: Parsed tcpvcon CSV or list of row dicts.
        network_summary: Parsed network_summary.json (tshark/pcap) dict.
        sample_proc: Target executable name for process attribution.

    Returns:
        Structured dictionary adhering to the IsoLens Unified Network Schema.
    """
    sample_name = sample_proc or "unknown"
    if not sample_proc:
        if sysmon_summary and sysmon_summary.get("sample_process"):
            sample_name = sysmon_summary["sample_process"]
        elif procmon_summary and procmon_summary.get("sample_process"):
            sample_name = procmon_summary["sample_process"]

    # 1. Gather DNS queries
    raw_dns: List[Any] = []
    if sysmon_summary and "dns_queries" in sysmon_summary:
        raw_dns.extend(sysmon_summary["dns_queries"])
    if network_summary and "dns_queries" in network_summary:
        raw_dns.extend(network_summary["dns_queries"])

    clean_dns, noise_dns = normalize_dns_queries(raw_dns, sample_proc=sample_name)

    # 2. Gather HTTP requests
    raw_http: List[Dict[str, Any]] = []
    if network_summary and "http_requests" in network_summary:
        raw_http.extend(network_summary["http_requests"])

    clean_http, noise_http = normalize_http_requests(raw_http, sample_proc=sample_name)

    # 3. Gather Connections (Sysmon + Procmon + TCPVcon + tshark)
    raw_conns: List[Dict[str, Any]] = []
    if sysmon_summary and "network_connections" in sysmon_summary:
        raw_conns.extend(sysmon_summary["network_connections"])
    if procmon_summary and "network_activity" in procmon_summary:
        raw_conns.extend(procmon_summary["network_activity"])
    if tcpvcon_data:
        if isinstance(tcpvcon_data, list):
            raw_conns.extend(tcpvcon_data)
    if network_summary and "tcp_conversations" in network_summary:
        raw_conns.extend(parse_tshark_conversations(network_summary["tcp_conversations"], sample_proc=sample_name))

    clean_conns, noise_conns = normalize_connections(raw_conns, sample_proc=sample_name)

    # 4. Extract unique IOCs
    iocs_domains: Set[str] = set()
    iocs_ips: Set[str] = set()
    iocs_urls: Set[str] = set()

    for d in clean_dns:
        if d.get("domain"):
            iocs_domains.add(d["domain"])
        for ip in d.get("resolved_ips", []):
            if ip and not is_noise_ip(ip):
                iocs_ips.add(ip)

    for h in clean_http:
        if h.get("host") and not is_noise_domain(h["host"]):
            iocs_domains.add(h["host"])
        if h.get("url"):
            iocs_urls.add(h["url"])

    for c in clean_conns:
        if c.get("dst_ip") and not is_noise_ip(c["dst_ip"]):
            iocs_ips.add(c["dst_ip"])
        if c.get("dst_host") and not is_noise_domain(c["dst_host"]):
            iocs_domains.add(c["dst_host"])

    return {
        "summary": {
            "sample_process": sample_name,
            "total_dns_queries": len(clean_dns) + len(noise_dns),
            "filtered_noise_dns": len(noise_dns),
            "clean_dns_count": len(clean_dns),
            "total_http_requests": len(clean_http) + len(noise_http),
            "filtered_noise_http": len(noise_http),
            "clean_http_count": len(clean_http),
            "total_connections": len(clean_conns) + len(noise_conns),
            "filtered_noise_connections": len(noise_conns),
            "clean_connections_count": len(clean_conns),
            "unique_domains": sorted(list(iocs_domains)),
            "unique_remote_ips": sorted(list(iocs_ips)),
        },
        "dns_queries": clean_dns,
        "http_requests": clean_http,
        "connections": clean_conns,
        "iocs": {
            "domains": sorted(list(iocs_domains)),
            "ips": sorted(list(iocs_ips)),
            "urls": sorted(list(iocs_urls)),
        },
        "filtered_noise": {
            "noise_domains_detected": sorted(list(set(d["domain"] for d in noise_dns))),
            "noise_connections_count": len(noise_conns),
        },
    }


def extract_network_from_sysmon_xml(
    xml_path: Union[str, Path],
    sample_proc: str = "",
) -> Dict[str, Any]:
    """Extract DNS queries and network connections directly from a Sysmon XML log."""
    p = Path(xml_path)
    if not p.is_file():
        return {"dns_queries": [], "network_connections": []}

    try:
        with open(p, "r", encoding="utf-16", errors="replace") as f:
            content = f.read()
        if not content.startswith("<"):
            with open(p, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
    except Exception:
        with open(p, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()

    events = re.findall(r"<Event [^>]*>.*?</Event>", content, re.DOTALL)
    dns_queries = []
    conns = []
    sample_proc_lower = sample_proc.lower() if sample_proc else ""

    for ev_str in events:
        ev_clean = re.sub(r' xmlns=[\'"][^\'"]*[\'"]', "", ev_str)
        try:
            root = ET.fromstring(ev_clean)
        except Exception:
            continue
        sys_el = root.find("System")
        eid = sys_el.find("EventID").text if sys_el is not None and sys_el.find("EventID") is not None else ""
        if eid not in ("3", "22"):
            continue
        ed = root.find("EventData")
        if ed is None:
            continue
        data = {d.get("Name"): d.text for d in ed.findall("Data")}
        img = (data.get("Image") or "").lower()
        if sample_proc_lower and sample_proc_lower not in img:
            continue

        if eid == "22":
            dns_queries.append({
                "domain": data.get("QueryName", ""),
                "resolved_ips": [r.strip() for r in (data.get("QueryResults") or "").split(";") if r.strip() and r.strip() != "-"],
                "process_name": data.get("Image") or sample_proc,
                "pid": data.get("ProcessId"),
                "timestamp": data.get("UtcTime"),
            })
        elif eid == "3":
            conns.append({
                "proto": data.get("Protocol", "TCP"),
                "src_ip": data.get("SourceIp", ""),
                "src_port": data.get("SourcePort", 0),
                "dst_ip": data.get("DestinationIp", ""),
                "dst_port": data.get("DestinationPort", 0),
                "dst_host": data.get("DestinationHostname", ""),
                "process_name": data.get("Image") or sample_proc,
                "pid": data.get("ProcessId"),
                "timestamp": data.get("UtcTime"),
            })
    return {"dns_queries": dns_queries, "network_connections": conns, "sample_process": sample_proc}


def extract_network_from_procmon_csv(
    csv_path: Union[str, Path],
    sample_proc: str = "",
) -> List[Dict[str, Any]]:
    """Extract TCP/UDP network operations directly from a Procmon CSV log."""
    records = []
    p = Path(csv_path)
    if not p.is_file():
        return records

    sample_proc_lower = sample_proc.lower() if sample_proc else ""
    with open(p, "r", encoding="utf-8-sig", errors="replace") as f:
        reader = csv.DictReader(f)
        for r in reader:
            pname = (r.get("Process Name") or "").lower()
            if sample_proc_lower and sample_proc_lower not in pname:
                continue
            op = r.get("Operation", "")
            if op.startswith("TCP") or op.startswith("UDP"):
                records.append({
                    "proto": "TCP" if op.startswith("TCP") else "UDP",
                    "path": r.get("Path", ""),
                    "process_name": r.get("Process Name") or sample_proc,
                    "time": r.get("Time of Day", ""),
                    "detail": r.get("Detail", ""),
                })
    return records


def normalize_report_directory(report_dir: Union[str, Path]) -> Dict[str, Any]:
    """Parse all network artifacts from an IsoLens analysis report directory."""
    rdir = Path(report_dir)
    artifacts = rdir / "artifacts" if (rdir / "artifacts").is_dir() else rdir

    def _load_json(p: Path) -> Optional[Dict[str, Any]]:
        if p.is_file():
            try:
                with open(p, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                return None
        return None

    def _load_csv(p: Path) -> List[Dict[str, str]]:
        if p.is_file():
            try:
                with open(p, "r", encoding="utf-8", errors="replace") as f:
                    return list(csv.DictReader(f))
            except Exception:
                return []
        return []

    sysmon = _load_json(artifacts / "sysmon" / "sysmon_summary.json")
    if not sysmon and (artifacts / "sysmon" / "sysmon_events.xml").is_file():
        sysmon = extract_network_from_sysmon_xml(artifacts / "sysmon" / "sysmon_events.xml")

    procmon = _load_json(artifacts / "procmon" / "procmon_summary.json")
    procmon_conns = []
    if (artifacts / "procmon" / "procmon.csv").is_file():
        procmon_conns = extract_network_from_procmon_csv(artifacts / "procmon" / "procmon.csv")

    tcpvcon = _load_csv(artifacts / "tcpvcon" / "tcpvcon_snapshot.csv")
    if procmon_conns:
        tcpvcon.extend(procmon_conns)

    network = _load_json(artifacts / "network" / "network_summary.json")

    return normalize_network_telemetry(
        sysmon_summary=sysmon,
        procmon_summary=procmon,
        tcpvcon_data=tcpvcon,
        network_summary=network,
    )


# ---------------------------------------------------------------------------
# CLI Entrypoint
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: python3 network_normalizer.py <report_dir | sysmon_summary.json>")
        sys.exit(1)

    target_path = Path(sys.argv[1])
    if target_path.is_dir():
        result = normalize_report_directory(target_path)
    else:
        with open(target_path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        result = normalize_network_telemetry(sysmon_summary=data)

    print(json.dumps(result, indent=2))
