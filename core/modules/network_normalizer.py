"""network_normalizer.py - Normalized Network Telemetry & Noise Filtering Module.

Ingests heterogeneous network artifacts from Windows Sandbox executions
(Sysmon DNS/Network, Procmon socket activity, TCPVcon connection tables, and HTTP logs),
filters out Windows OS background noise (NCSI, telemetry, mDNS, LLMNR, WPAD, CRL/OCSP,
and host-guest agent management traffic), and outputs a normalized, structured JSON
representation optimized for AI models, threat intelligence, and IOC extraction.
"""

from __future__ import annotations

import csv
import ipaddress
import json
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple, Union


