def normalize_dns_queries(
    raw_queries: List[Any],
    sample_proc: str = "",
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Normalize and filter DNS queries from Sysmon or network logs.

    Returns:
        (clean_queries, noise_queries)
    """
    clean: List[Dict[str, Any]] = []
    noise: List[Dict[str, Any]] = []
    seen_clean_domains: Set[str] = set()

    for item in raw_queries:
        if isinstance(item, str):
            domain = item.strip()
            query_record = {
                "domain": domain,
                "query_type": "A",
                "resolved_ips": [],
                "process_name": sample_proc or "unknown",
                "pid": None,
                "timestamp": None,
            }
        elif isinstance(item, dict):
            domain = item.get("domain") or item.get("QueryName") or item.get("query_name") or item.get("query") or ""
            domain = str(domain).strip()
            raw_results = item.get("resolved_ips") or item.get("QueryResults") or []
            if isinstance(raw_results, str):
                resolved = [r.strip() for r in raw_results.split(";") if r.strip()]
            else:
                resolved = list(raw_results)

            query_record = {
                "domain": domain,
                "query_type": item.get("query_type", "A"),
                "resolved_ips": resolved,
                "process_name": item.get("process_name") or item.get("Image") or sample_proc or "unknown",
                "pid": item.get("pid") or item.get("ProcessId"),
                "timestamp": item.get("timestamp") or item.get("TimeCreated"),
            }
        else:
            continue

        if not domain:
            continue

        if is_noise_domain(domain):
            query_record["is_noise"] = True
            noise.append(query_record)
        else:
            query_record["is_noise"] = False
            # Deduplicate by domain for clean representation
            if domain.lower() not in seen_clean_domains:
                seen_clean_domains.add(domain.lower())
                clean.append(query_record)

    return clean, noise


def normalize_http_requests(
    raw_http: List[Dict[str, Any]],
    sample_proc: str = "",
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Normalize and filter HTTP requests (from tshark / pcap / fakenet).

    Returns:
        (clean_http, noise_http)
    """
    clean: List[Dict[str, Any]] = []
    noise: List[Dict[str, Any]] = []

    for item in raw_http:
        if not isinstance(item, dict):
            continue

        host = (item.get("host") or "").strip()
        uri = (item.get("uri") or item.get("path") or "/").strip()
        method = (item.get("method") or "GET").upper().strip()
        port = item.get("port", 80)
        try:
            port = int(port)
        except (ValueError, TypeError):
            port = 80

        record = {
            "method": method,
            "host": host,
            "port": port,
            "uri": uri,
            "user_agent": item.get("user_agent") or item.get("User-Agent") or "",
            "process_name": item.get("process_name") or sample_proc or "unknown",
            "pid": item.get("pid"),
            "timestamp": item.get("timestamp"),
            "url": f"http://{host}:{port}{uri}" if port != 80 else f"http://{host}{uri}",
        }

        # Check for noise
        is_noisy = (
            not host
            or is_noise_domain(host)
            or is_noise_ip(host)
            or is_noise_port(port)
            or uri in NOISE_HTTP_URIS
        )

        record["is_noise"] = is_noisy
        if is_noisy:
            noise.append(record)
        else:
            clean.append(record)

    return clean, noise


def normalize_connections(
    raw_conns: List[Dict[str, Any]],
    sample_proc: str = "",
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Normalize socket connection records (from Sysmon Event 3, Procmon, or TCPVcon).

    Returns:
        (clean_conns, noise_conns)
    """
    clean: List[Dict[str, Any]] = []
    noise: List[Dict[str, Any]] = []
    seen: Set[str] = set()

    for item in raw_conns:
        if not isinstance(item, dict):
            continue

        proto = (item.get("proto") or item.get("Protocol") or "TCP").upper()

        # Handle Procmon path format: 'WindowsSandbox:65283 -> 192.0.2.123:http'
        path_str = item.get("path", "")
        if " -> " in path_str:
            src_str, dst_str = path_str.split(" -> ", 1)
            src_ip, src_port = parse_endpoint(src_str)
            dst_ip, dst_port = parse_endpoint(dst_str)
            dst_host = item.get("dst_host", "")
        else:
            src_ip = item.get("src_ip", "")
            src_port = item.get("src_port", 0)
            dst_ip = item.get("dst_ip") or item.get("DestinationIp", "")
            dst_port = item.get("dst_port") or item.get("DestinationPort", 0)
            dst_host = item.get("dst_host") or item.get("DestinationHostname", "")

            # If src/dst were passed as 'IP:Port' strings (Sysmon format)
            if ":" in str(item.get("src", "")):
                src_ip, src_port = parse_endpoint(item["src"])
            if ":" in str(item.get("dst", "")):
                dst_ip, dst_port = parse_endpoint(item["dst"])

        try:
            dst_port = int(dst_port)
        except (ValueError, TypeError):
            dst_port = PORT_NAME_MAP.get(str(dst_port).lower(), 0)

        record = {
            "proto": proto,
            "src_ip": src_ip,
            "src_port": src_port,
            "dst_ip": dst_ip,
            "dst_port": dst_port,
            "dst_host": dst_host,
            "process_name": item.get("image") or item.get("Image") or item.get("Process") or sample_proc or "unknown",
            "pid": item.get("pid") or item.get("PID"),
            "timestamp": item.get("time") or item.get("TimeCreated"),
        }

        # Check noise
        is_noisy = (
            is_noise_ip(dst_ip)
            or (bool(dst_host) and is_noise_domain(dst_host))
            or is_noise_port(dst_port)
            or is_noise_port(src_port)
        )

        record["is_noise"] = is_noisy
        if is_noisy:
            noise.append(record)
        else:
            key = f"{proto}:{dst_ip}:{dst_port}"
            if key not in seen:
                seen.add(key)
                clean.append(record)

    return clean, noise


def parse_tshark_conversations(conv_text: str, sample_proc: str = "") -> List[Dict[str, Any]]:
    """Parse text output of tshark TCP conversations table into connection dicts."""
    records: List[Dict[str, Any]] = []
    if not conv_text or not isinstance(conv_text, str):
        return records

    pattern = re.compile(r"([0-9a-zA-Z\.\-\:\[\]]+)\s+<\->\s+([0-9a-zA-Z\.\-\:\[\]]+)")
    for line in conv_text.splitlines():
        match = pattern.search(line)
        if match:
            src_ep, dst_ep = match.group(1), match.group(2)
            src_ip, src_port = parse_endpoint(src_ep)
            dst_ip, dst_port = parse_endpoint(dst_ep)
            records.append({
                "proto": "TCP",
                "src_ip": src_ip,
                "src_port": src_port,
                "dst_ip": dst_ip,
                "dst_port": dst_port,
                "process_name": sample_proc or "unknown",
            })
    return records


